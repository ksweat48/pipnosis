-- Function to update strategy performance automatically
CREATE OR REPLACE FUNCTION update_strategy_performance()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO strategy_performance (
    user_id, strategy_version, period, period_start, period_end,
    total_trades, winning_trades, losing_trades
  )
  VALUES (
    NEW.user_id, NEW.strategy_version, 'daily',
    DATE_TRUNC('day', NEW.exit_time),
    DATE_TRUNC('day', NEW.exit_time) + INTERVAL '1 day',
    1,
    CASE WHEN NEW.pnl > 0 THEN 1 ELSE 0 END,
    CASE WHEN NEW.pnl < 0 THEN 1 ELSE 0 END
  )
  ON CONFLICT (user_id, strategy_version, period, period_start)
  DO UPDATE SET
    total_trades = strategy_performance.total_trades + 1,
    winning_trades = strategy_performance.winning_trades + (CASE WHEN NEW.pnl > 0 THEN 1 ELSE 0 END),
    losing_trades = strategy_performance.losing_trades + (CASE WHEN NEW.pnl < 0 THEN 1 ELSE 0 END),
    total_pnl = strategy_performance.total_pnl + NEW.pnl,
    updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger on ai_demo_trades to update performance
CREATE TRIGGER update_performance_on_trade_close
  AFTER UPDATE OF status ON ai_demo_trades
  FOR EACH ROW
  WHEN (NEW.status IN ('closed', 'stopped', 'target_hit') AND OLD.status = 'open')
  EXECUTE FUNCTION update_strategy_performance();